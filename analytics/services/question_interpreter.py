
import json
import os

from google import genai
from google.genai import types


SUPPORTED_INTENTS = {
    "total_revenue",
    "top_product",
    "lowest_product",
    "product_revenue",
    "top_category",
    "top_region",
    "lowest_region",
    "regional_comparison",
    "region_revenue",
    "monthly_revenue",
    "highest_revenue_month",
    "average_monthly_revenue",
    "monthly_revenue_change",
    "total_transactions",
    "total_quantity_sold",
    "average_order_value",
    "total_discount",
    "top_sales_channel",
    "returned_transactions",
    "unknown",
}


def interpret_question(question):
    """
    Identify the requested analytics operation and extract
    relevant parameters.

    Gemini interprets the question.
    Django ORM performs the actual calculations.
    """

    if not question or not question.strip():
        raise ValueError("Question cannot be empty.")

    api_key = os.getenv("GEMINI_API_KEY")

    if not api_key:
        raise RuntimeError("GEMINI_API_KEY is not configured.")

    client = genai.Client(api_key=api_key)

    prompt = f"""
You are an intent classifier for a sales analytics chatbot.

Choose exactly one intent from the following:

REVENUE:
- total_revenue: asks for total revenue.

PRODUCT:
- top_product: asks which product generated the highest revenue.
- lowest_product: asks which product generated the lowest revenue.
- product_revenue: asks for revenue generated by a specific product.

CATEGORY:
- top_category: asks which category generated the highest revenue.

REGION:
- top_region: asks which region generated the highest revenue.
- lowest_region: asks which region generated the lowest revenue.
- regional_comparison: asks to compare revenue across regions
  or show revenue for all regions.
- region_revenue: asks for revenue generated by a specific region.

MONTHLY:
- monthly_revenue: asks for month-wise revenue or monthly trends.
- highest_revenue_month: asks which month generated the highest revenue.
- average_monthly_revenue: asks for average monthly revenue.
- monthly_revenue_change: asks how revenue changed between months.

SALES:
- total_transactions: asks for the number of completed transactions.
- total_quantity_sold: asks for the total quantity of products sold.
- average_order_value: asks for average order value.

DISCOUNTS:
- total_discount: asks for total discount provided.

CHANNEL:
- top_sales_channel: asks which sales channel generated the highest revenue.

RETURNS:
- returned_transactions: asks for the number of returned transactions.

UNKNOWN:
- unknown: unrelated, unsupported or unclear questions.

Parameter extraction:
1. For product_revenue, extract product_name.
2. For region_revenue, extract region_name.
3. For every other intent, both parameters must be null.
4. Do not invent product or region names.
5. If a required parameter cannot be identified, use unknown.
6. Do not calculate figures.
7. Do not generate SQL.
8. Return only the requested JSON.

User question:
{question}
"""

    response = client.models.generate_content(
        model="gemini-3.5-flash-lite",
        contents=prompt,
        config=types.GenerateContentConfig(
            response_mime_type="application/json",
            response_json_schema={
                "type": "OBJECT",
                "properties": {
                    "intent": {
                        "type": "STRING",
                        "enum": sorted(SUPPORTED_INTENTS),
                    },
                    "analytics_type": {
                        "type": "STRING",
                        "enum": ["descriptive"],
                    },
                    "product_name": {
                        "type": ["STRING", "NULL"],
                    },
                    "region_name": {
                        "type": ["STRING", "NULL"],
                    },
                },
                "required": [
                    "intent",
                    "analytics_type",
                    "product_name",
                    "region_name",
                ],
            },
        ),
    )

    result = json.loads(response.text)

    intent = result.get("intent")

    if intent not in SUPPORTED_INTENTS:
        raise ValueError("Gemini returned an unsupported intent.")

    product_name = result.get("product_name")
    region_name = result.get("region_name")

    if intent == "product_revenue":
        if not isinstance(product_name, str) or not product_name.strip():
            intent = "unknown"
            product_name = None
        else:
            product_name = product_name.strip()
    else:
        product_name = None

    if intent == "region_revenue":
        if not isinstance(region_name, str) or not region_name.strip():
            intent = "unknown"
            region_name = None
        else:
            region_name = region_name.strip()
    else:
        region_name = None

    return {
        "intent": intent,
        "analytics_type": "descriptive",
        "product_name": product_name,
        "region_name": region_name,
    }
